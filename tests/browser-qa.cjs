const { chromium } = require("playwright");
const fs = require("fs");
const path = require("path");

(async () => {
  const browser = await chromium.launch({ headless: true, channel: process.platform === "win32" ? "msedge" : undefined });
  const results = [];
  const check = (name, pass, detail = "") => { results.push({ name, pass: Boolean(pass), detail }); if (!pass) throw new Error(`${name}: ${detail}`); };
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1, acceptDownloads: true });
  await page.goto("http://127.0.0.1:4174", { waitUntil: "networkidle" });
  await page.evaluate(() => localStorage.clear());
  await page.reload({ waitUntil: "networkidle" });
  check("cases page loads", await page.locator("#cases-title").isVisible());
  check("portfolio contains the public example and four demo cases", await page.locator("#caseList [data-open-case]").count() === 5);
  check("primary navigation is limited to two destinations", await page.locator(".topbar [data-view]").count() === 2);
  check("external requirement sections are absent", await page.locator("#knowledge, #evaluation, #researchList, #sourceMap").count() === 0);
  await page.locator("#caseList [data-open-case]").first().click();
  check("public Microsoft case opens in evidence workspace", await page.locator("#caseTitle").textContent() === "Microsoft");
  check("both evidence excerpts are visible", await page.locator("#claimText").isVisible() && await page.locator("#evidenceText").isVisible());
  check("matching public disclosures are classified as supported", (await page.locator("#findingStatus").textContent()).includes("supported"));
  await page.locator("[data-source-side='claim']").click();
  check("source provenance opens", await page.locator("#sourceDialog[open]").isVisible() && (await page.locator("#sourceDialogContent").textContent()).includes("MSFT-ESR-2025"));
  check("public source links to the original", (await page.locator("#sourceDialogContent .source-original").getAttribute("href") || "").includes("microsoft.com"));
  await page.locator("#sourceDialog button[value='cancel']").click();
  await page.locator("button[data-decision='confirmed']").click();
  await page.locator("#reviewNote").fill("QA review note with source context.");
  await page.locator("#saveReview").click();
  check("review decision persists locally", (await page.locator("#saveState").textContent()).includes("Saved"));
  await page.locator("[data-scope='reviewed']").click();
  check("reviewed filter works", (await page.locator("#findingsTable").textContent()).includes("confirmed"));
  await page.locator("button[data-view='documents']").click();
  check("document library lists source artifacts", await page.locator("#documentLibrary [data-document-id]").count() === 10);
  await page.locator("#documentSearch").fill("Northstar");
  check("document search filters records", await page.locator("#documentLibrary [data-document-id]").count() === 2);
  await page.locator("[data-action-view='import']").first().click();
  await page.locator("#primaryText").fill("Primary only");
  await page.locator("#analyzeButton").click();
  check("incomplete import is blocked with inline error", await page.locator("#importValidation").isVisible());
  fs.mkdirSync(path.join(__dirname, "screenshots"), { recursive: true });
  await page.locator("#import [data-action-view='cases']").click();
  await page.screenshot({ path: path.join(__dirname, "screenshots", "desktop.png"), fullPage: true });
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1 });
  await mobile.goto("http://127.0.0.1:4174#workspace", { waitUntil: "networkidle" });
  check("mobile evidence remains visible", await mobile.locator("#claimText").isVisible() && await mobile.locator("#evidenceText").isVisible());
  check("mobile has no horizontal overflow", await mobile.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth + 1));
  check("mobile review controls remain operable", await mobile.locator("button[data-decision='confirmed']").isVisible());
  await mobile.screenshot({ path: path.join(__dirname, "screenshots", "mobile.png"), fullPage: true });
  await browser.close();
  const report = { runAt: new Date().toISOString(), passed: results.filter(result => result.pass).length, total: results.length, results };
  fs.writeFileSync(path.join(__dirname, "browser-qa-results.json"), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
})().catch(error => { console.error(error.stack); process.exit(1); });
