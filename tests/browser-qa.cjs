const { chromium } = require("playwright");
const fs = require("fs");
const path = require("path");

(async () => {
  const browser = await chromium.launch({ headless: true, channel: process.platform === "win32" ? "msedge" : undefined });
  const results = [];
  const check = (name, pass, detail = "") => { results.push({ name, pass: Boolean(pass), detail }); if (!pass) throw new Error(`${name}: ${detail}`); };
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1, acceptDownloads: true });
  await page.goto("http://127.0.0.1:4174", { waitUntil: "networkidle" });
  await page.evaluate(() => localStorage.clear());
  await page.reload({ waitUntil: "networkidle" });
  check("portfolio overview loads", await page.locator("#overview-title").isVisible());
  check("portfolio contains four seeded cases", await page.locator("#caseQueue .queue-item").count() === 4);
  await page.locator("#openDemoButton").click();
  check("demo opens in evidence workspace", await page.locator("#caseTitle").textContent() === "Atlas Components — FY2025 review");
  check("both evidence excerpts visible", await page.locator("#claimText").isVisible() && await page.locator("#evidenceText").isVisible());
  check("contradiction state is explicit", (await page.locator("#findingStatus").textContent()).includes("potential contradiction"));
  await page.locator("[data-source-side='claim']").click();
  check("source provenance dialog opens", await page.locator("#sourceDialog[open]").isVisible() && (await page.locator("#sourceDialogContent").textContent()).includes("DOC-ATL-SR25"));
  await page.locator("#sourceDialog button[value='cancel']").click();
  await page.locator("button[data-decision='confirmed']").click();
  await page.locator("#reviewNote").fill("QA review note with source context.");
  await page.locator("#saveReview").click();
  check("review decision persists locally", (await page.locator("#saveState").textContent()).includes("Saved"));
  await page.locator("[data-scope='reviewed']").click();
  check("reviewed queue filter works", (await page.locator("#findingsTable").textContent()).includes("confirmed"));
  await page.locator("button[data-view='documents']").click();
  check("document library lists source artifacts", await page.locator("#documentLibrary .document-row").count() >= 9);
  await page.locator("#documentSearch").fill("Northstar");
  check("document search filters records", await page.locator("#documentLibrary .document-row").count() === 3);
  await page.locator("button[data-view='knowledge']").click();
  check("research library includes ten papers", await page.locator("#researchList .research-item").count() === 10);
  await page.locator("[data-knowledge-tab='sources']").click();
  check("source map includes official and open sources", await page.locator("#sourceMap .source-entry").count() >= 12);
  await page.locator("button[data-view='import']").click();
  await page.locator("#primaryText").fill("Primary only");
  await page.locator("#analyzeButton").click();
  check("incomplete import is blocked with inline error", await page.locator("#importValidation").isVisible());
  await page.locator("#searchTrigger").click();
  await page.locator("#commandInput").fill("evaluation");
  check("global search returns evaluation", (await page.locator("#commandResults").textContent()).includes("Evaluation"));
  await page.locator("#commandDialog button[value='cancel']").click();
  await page.locator("#profileButton").click();
  await page.locator("#highContrast").check();
  check("accessibility preference applies", await page.locator("body").evaluate(el => el.classList.contains("high-contrast")));
  await page.locator("#highContrast").uncheck();
  await page.locator("#settingsDialog button[value='cancel']").click();
  await page.locator("button[data-view='overview']").click();
  await page.locator("#toastRegion").evaluate(el => { el.innerHTML = ""; });
  fs.mkdirSync(path.join(__dirname, "screenshots"), { recursive: true });
  await page.screenshot({ path: path.join(__dirname, "screenshots", "desktop.png"), fullPage: true });
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1 });
  await mobile.goto("http://127.0.0.1:4174#workspace", { waitUntil: "networkidle" });
  check("mobile evidence remains visible", await mobile.locator("#claimText").isVisible() && await mobile.locator("#evidenceText").isVisible());
  check("mobile has no horizontal overflow", await mobile.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth + 1));
  check("mobile provenance controls remain operable", await mobile.locator("[data-source-side='claim']").isVisible());
  await mobile.screenshot({ path: path.join(__dirname, "screenshots", "mobile.png"), fullPage: true });
  await browser.close();
  const report = { runAt: new Date().toISOString(), passed: results.filter(r => r.pass).length, total: results.length, results };
  fs.writeFileSync(path.join(__dirname, "browser-qa-results.json"), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
})().catch(async error => { console.error(error.stack); process.exit(1); });
